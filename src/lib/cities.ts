const CYR: Record<string, string> = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', ђ: 'd', е: 'e', ж: 'z', з: 'z', и: 'i', ј: 'j', к: 'k', л: 'l', љ: 'lj',
  м: 'm', н: 'n', њ: 'nj', о: 'o', п: 'p', р: 'r', с: 's', т: 't', ћ: 'c', у: 'u', ф: 'f', х: 'h', ц: 'c', ч: 'c', џ: 'dz', ш: 's',
};

/** Za poređenje: bez kvačica, latinica, "đ"/"dj" → "d" — "Sabac", "Šabac" i "Шабац" su isto. */
export function normalizeCityName(s: string): string {
  return s
    .toLowerCase()
    .replace(/[а-яђјљњћџ]/g, (ch) => CYR[ch] ?? ch)
    .replace(/đ/g, 'd')
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/dj/g, 'd')
    .replace(/[-\s]+/g, ' ')
    .trim();
}

const NORMALIZED = CITIES.map((c) => ({ city: c, key: normalizeCityName(c.name) }));

/** Gradovi čiji naziv sadrži upit; prvo oni koji njime počinju, pa oni gdje mu počinje neka riječ. */
export function searchCities(query: string, limit = 30): CityDef[] {
  const q = normalizeCityName(query);
  if (!q) return [];
  const rank = (key: string) => (key.startsWith(q) ? 0 : key.includes(` ${q}`) ? 1 : 2);
  return NORMALIZED.filter((c) => c.key.includes(q))
    .sort((a, b) => rank(a.key) - rank(b.key))
    .slice(0, limit)
    .map((c) => c.city);
}
